    /** 地支 → 五行（日应/鸟兽兆用）。 */
    private static String zhiFive(final String zhi) {
        if (zhi == null || zhi.isBlank()) {
            return "";
        }
        char z = zhi.charAt(0);
        if ("寅卯".indexOf(z) >= 0) {
            return "木";
        }
        if ("巳午".indexOf(z) >= 0) {
            return "火";
        }
        if ("申酉".indexOf(z) >= 0) {
            return "金";
        }
        if ("亥子".indexOf(z) >= 0) {
            return "水";
        }
        if ("辰戌丑未".indexOf(z) >= 0) {
            return "土";
        }
        return "";
    }

    private static String riYingNote(final String dayZhi) {
        String f = zhiFive(dayZhi);
        if (f.isEmpty()) {
            return "";
        }
        return "〔日应〕" + dayZhi + "日，" + RI_YING.get(f) + "（原卷之三·占卜十应诀）。";
    }

