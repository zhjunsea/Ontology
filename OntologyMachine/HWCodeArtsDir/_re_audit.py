def s(t):
    return ''.join(T2S.get(c,c) for c in t)

g=rdflib.Graph(); g.parse(r'..\OntologyFrameworkZiWeiDouShu\ontology\ziweidoushu-all.owl', format='xml')
hay=[]
for subj,p,o in g:
    if str(p).endswith('label') or isinstance(o, rdflib.Literal):
        hay.append(str(o))
    hay.append(str(subj)); hay.append(str(p))
hay=' | '.join(hay)
hay=s(hay).replace(' ','')
def norm(t): return s(t).replace(' ','')

titles=[]
for fn in ['_re_c2_titles.txt','_re_c3_titles.txt','_re_c4_titles.txt']:
    for line in io.open(fn,encoding='utf-8'):
        m=re.match(r'^\s*\d+\s+(\S.*)$', line.rstrip('\n'))
        if not m: continue
        t=m.group(1).strip()
        if t.startswith('====='): continue
        if t in ('紫微斗數全書','卷一','卷二','卷三','姊妹计划','数据项') or '紫微斗数全书' in t or '紫微斗數全書卷' in t: continue
        titles.append(t)
seen=set(); uniq=[]
for t in titles:
    if t in seen: continue
    seen.add(t); uniq.append(t)
miss=[]
for t in uniq:
    tn=norm(t)
    if tn in hay: continue
    core=re.sub(r'^[論论安定起]','',tn); core=re.sub(r'(訣|诀|例|曰|論|论|赋|賦)$','',core)
    if core and core in hay: continue
    miss.append(t)
print('MATCHED:', len(uniq)-len(miss), '/', len(uniq))
print('--- unmatched ---')
for t in miss: print('  -', t, ' => ', norm(t))
